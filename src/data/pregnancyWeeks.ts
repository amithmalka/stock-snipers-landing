export function getWeekContent(week: number): PregnancyWeek {
  if (week < 4) return PREGNANCY_WEEKS[0];
  if (week > 42) return PREGNANCY_WEEKS[PREGNANCY_WEEKS.length - 1];
  return PREGNANCY_WEEKS.find((w) => w.week === week) ?? PREGNANCY_WEEKS[0];
}

export function calculatePregnancyWeek(lmpIso: string, todayIso?: string): { week: number; days: number; totalDays: number } {
  const lmp = new Date(lmpIso);
  const today = todayIso ? new Date(todayIso) : new Date();
  const diffMs = today.getTime() - lmp.getTime();
  const totalDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
  const week = Math.floor(totalDays / 7);
  const days = totalDays % 7;
  return { week, days, totalDays };
}

export function calculateDueDate(lmpIso: string): string {
  // Naegele's rule: LMP + 280 days
  const lmp = new Date(lmpIso);
  const due = new Date(lmp.getTime() + 280 * 24 * 60 * 60 * 1000);
  return due.toISOString().slice(0, 10);
}

export function lmpFromWeek(week: number, days = 0, todayIso?: string): string {
  const today = todayIso ? new Date(todayIso) : new Date();
  const totalDays = week * 7 + days;
  const lmp = new Date(today.getTime() - totalDays * 24 * 60 * 60 * 1000);
  return lmp.toISOString().slice(0, 10);
}
